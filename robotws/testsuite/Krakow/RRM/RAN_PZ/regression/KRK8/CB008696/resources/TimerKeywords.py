# TimerKeywords.py
import time
from robot.api import logger
from robot.api.deco import keyword


@keyword("Start Timer")
def start_timer(duration_in_seconds: int) -> float:
    """
    Starts a timer and returns the calculated end time.
    The end time is the current time + duration.

    :param duration_in_seconds: How long the timer should run, in seconds.
    :return: The absolute timestamp (float) when the timer will end.
    """
    end_time = time.time() + int(duration_in_seconds)
    logger.warn(f"Timer started. Will end in {duration_in_seconds} seconds.")
    return end_time


@keyword("Wait For Timer")
def wait_for_timer(end_time: float):
    """
    Waits until the current time is past the provided end_time.
    If the time has already passed, it continues immediately.

    :param end_time: The absolute timestamp to wait for, generated by "Start Timer".
    """
    current_time = time.time()
    if current_time < end_time:
        wait_duration = end_time - current_time
        logger.warn(f"Waiting for the remaining {wait_duration:.2f} seconds...")
        time.sleep(wait_duration)
    logger.warn("Timer finished. Continuing execution.")
