def check_msc(packets, field_name_list, message_sequence):
    """ Verifies if message sequence was found in the packet sequence or not.
    :param  list packets: list of packets
    :param list field_name_list: list of field name
    :param str message_sequence: sequence of message strings
    :param str timezone: timezone offset

    :return: Raise assertion error if message sequence was not found

    """
    actual_msc_list = []
    for packet in packets:
        for field_name in field_name_list:
            for value in packet.findall(field_name):
                actual_msc_list.append(value.showname)
    actual_msc = "\n".join(actual_msc_list)
    assert re.search(message_sequence, actual_msc, re.S), actual_msc


