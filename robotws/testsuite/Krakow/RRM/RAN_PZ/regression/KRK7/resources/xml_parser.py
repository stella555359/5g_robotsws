def find_nearest_packet_after(packet_list, packet_type_to_find, reference_packet_type, index_of_reference):
    """ Returns index of nearest packet_type_to_find occurence after nth packet of another type
    :param list packet_list: list of all packets collected
    :param str packet_type_to_find: type of searching package, currently supports values:
        - "RRCReconfiguration"
        - "SgNBModificationRequest"
        - "Measurement Report"
    :param reference_packet_type: type of packet used to be a reference for packet_type_to_find,
    currently supports values:
        - "RRCReconfiguration"
        - "SgNBModificationRequest"
        - "Measurement Report"
    :param int index_of_reference: looks for n-th occurence of packet_type_to_find
    to determine first index to use for searching
    """

    packets_type_indexes = map_packet_types_with_indexes(packet_list)

    if packet_type_to_find not in packets_type_indexes.keys() or \
            reference_packet_type not in packets_type_indexes.keys():
        raise Exception('There are no packet types within packet_type_indexes!')

    absolute_index_of_reference_packet = None
    for i, absolute_index in enumerate(packets_type_indexes[reference_packet_type]):
        if i == (index_of_reference-1):
            absolute_index_of_reference_packet = absolute_index
            break

    absolute_index_packet_to_find = None
    for i, absolute_index in enumerate(packets_type_indexes[packet_type_to_find]):
        if absolute_index > absolute_index_of_reference_packet:
            absolute_index_packet_to_find = absolute_index
            break
    print('packet_list[', absolute_index_packet_to_find, ']')
    return packet_list[absolute_index_packet_to_find]


