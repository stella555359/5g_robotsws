def has_rrcreconfiguration_configured_proper_event(packet, event_type):

    found_events = []  # should has at least one item

    paths_for_added_events = packet.paths("x2ap/(.*?)/nr-rrc.ReportConfigToAddMod_element/nr-rrc.reportConfigId")

    for path in paths_for_added_events:

        reportConfigIds = packet.xpath(path)
        paths_of_eventId = path + "//..//nr-rrc.eventId"
        eventIds = packet.xpath(paths_of_eventId)

        if 'event{}'.format(event_type) in eventIds[0].showname:
            found_events.append(eventIds[0])

    if not len(found_events):
        raise Exception(
            'RRCReconfiguration should has configured at least one Event {}, but no one found!'.format(event_type))


def update_measId_with_event_types(packet, previous_measId_list):

    reportCondfigIds_to_remove = []
    previous_reportConfigIds = {measId['reportConfigId']: measId['eventType'] for measId in previous_measId_list}
    report_config_Ids_events = get_reportConfigId_with_associated_events(packet)
    report_config_Ids_events.update(previous_reportConfigIds)

    paths_of_reportConfigId = packet.paths(
                "x2ap/(.*?)/nr-rrc.reportConfigToRemoveList/(.*?)/nr-rrc.ReportConfigId")

    for path in paths_of_reportConfigId:
        reportConfigId = packet.xpath(path)[0]
        reportCondfigIds_to_remove.append(reportConfigId.show)

    filtered_reportConfigIds_with_events = {}

    for reportConfigId in report_config_Ids_events.keys():
        if reportConfigId not in reportCondfigIds_to_remove:
            filtered_reportConfigIds_with_events[reportConfigId] = report_config_Ids_events[reportConfigId]

    measIds = []
    paths_of_measId = packet.paths("x2ap/(.*?)/nr-rrc.measIdToAddModList/(.*?)/nr-rrc.measId")
    for path in paths_of_measId:
        path_of_measId = packet.xpath(path)[0]
        paths_of_reportConfigId = path + "//..//nr-rrc.reportConfigId"
        paths_of_measObjId = path + "//..//nr-rrc.measObjectId"
        reportConfigIds = packet.xpath(paths_of_reportConfigId)[0]
        measObjId = packet.xpath(paths_of_measObjId)[0]
        eventIds = packet.xpath(path + "//..//nr-rrc.eventId")
        measIds.append({'measId': path_of_measId.show,
                        'eventType': filtered_reportConfigIds_with_events[reportConfigIds.show],
                        'reportConfigId': reportConfigIds.show,
                        'measObjectId': measObjId.show})
    return measIds


def are_meas_ids_list_equal(meas_ids_1, meas_ids_2):
    if not len(meas_ids_1) == len(meas_ids_2):
        raise Exception('The meas id list of two packets are not equal!')

    def has_meas_ids_list_value(meas_ids, meas_id, report_config_id, meas_object_id):
        for measid in meas_ids:
            if measid['measId'] == meas_id and measid['reportConfigId'] == report_config_id and \
               measid['measObjectId'] == meas_object_id:
                return True
        return False

    for meas_id1 in meas_ids_1:
        if not has_meas_ids_list_value(meas_ids_2,
                                       meas_id1['measId'],
                                       meas_id1['reportConfigId'],
                                       meas_id1['measObjectId']):
            raise Exception('There are differences between two meas id lists!')


