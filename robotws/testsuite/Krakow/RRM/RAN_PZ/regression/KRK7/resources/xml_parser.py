def is_measId_order_correct(packet, nrhoifs, event_type=None, rsrp_value=None, time_trigger=None):
    if event_type and rsrp_value and time_trigger:
        event_type_report_config_id = find_report_config(packet, event_type, rsrp_value, time_trigger)
    else:
        event_type_report_config_id = get_reportConfigId_for_event_a4(packet)
    meas_ids = get_measId_from_packet(packet)
    event_meas_ids = filter_measId_for_event_type(meas_ids, event_type_report_config_id)
    meas_objects_related_with_event_type = filter_measObj_for_event_type(meas_ids, event_type_report_config_id)
    meas_object_ids = get_all_measObjectId_with_frequencies_ordered_by_priority(packet,
                                                                                nrhoifs,
                                                                                meas_objects_related_with_event_type)
    logger.info('All measId elements: {}'.format(meas_ids))
    logger.info('All measId for event A4 (reportConfigId = {}): {}'.format(event_type_report_config_id, event_meas_ids))

    for a4_meas_id_report_config_id, meas_object_id in zip(event_meas_ids, meas_object_ids):
        if not a4_meas_id_report_config_id['measObjectId'] == meas_object_id:
            raise Exception('Order of meas_id does not correspond to priorities! measId = {} '
                            'should has measObjectId = {}, but its {}!'
                            .format(a4_meas_id_report_config_id['measId'],
                                    meas_object_id,
                                    a4_meas_id_report_config_id['measObjectId']))
    logger.console(event_meas_ids)
    return event_meas_ids


