def get_time_and_parameter_packets_based_on_message(packet_list, parameter, message):
    list_result = []
    if not isinstance(parameter, list):
        parameter = [parameter]
    packets = get_packets_based_on_message(packet_list=packet_list, message=message)
    for packet in packets:
        result = {}
        event_time = get_packet_time(packet)
        result['time'] = float(event_time)
        for param in parameter:
            param_name = param.split('.')[-1]
            param_value = [getattr(element, 'show') for element in packet.findall(param)]
            result[param_name] = param_value
            if result not in list_result:
                list_result.append(result)
    return list_result


