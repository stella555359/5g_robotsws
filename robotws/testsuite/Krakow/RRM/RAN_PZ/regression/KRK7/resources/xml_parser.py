def find_report_config(packet, event_type, rsrp_value, time_trigger):
    paths_of_reportConfigId = packet.paths(
                "x2ap/(.*?)/nr-rrc.ReportConfigToAddMod_element/nr-rrc.reportConfigId")
    for path in paths_of_reportConfigId:
        reportConfigIds = packet.xpath(path)
        paths_of_eventId = path + "//..//nr-rrc.eventId"
        eventIds = packet.xpath(paths_of_eventId)
        for ids in eventIds:
            event = 'event{}'.format(event_type)
            if event in ids.showname:
                path_to_rsrp = paths_of_eventId + "/..//nr-rrc.measTriggerQuantity.rsrp"
                path_to_time_trigger = paths_of_eventId + "/..//nr-rrc.timeToTrigger"
                if packet.xpath(path_to_time_trigger) and packet.xpath(path_to_rsrp):
                    time_to_trigger = packet.xpath(path_to_time_trigger)[0]
                    rsrp_values = packet.xpath(path_to_rsrp)[0]
                    if rsrp_values.show == str(rsrp_value) and time_trigger in time_to_trigger.showname:
                        report_config_id = reportConfigIds[0].show
                        logger.info("A4_measurement_id: reportconfigid {}".format(report_config_id))
                        return report_config_id
                else:
                    break
    raise Exception("A4_measurement_id: reportconfigid not found")


def find_measurament_object_id(packet, ssb_freq):
    paths_of_measId = packet.paths("x2ap/(.*?)/nr-rrc.MeasObjectToAddMod_element/nr-rrc.measObjectId")
    for path in paths_of_measId:
        measobjid = packet.xpath(path)
        paths_of_ssbfreq = path + "//..//nr-rrc.ssbFrequency"
        ssb_freqs = packet.xpath(paths_of_ssbfreq)
        for freq in ssb_freqs:
            if str(ssb_freq) == freq.show:
                meas_obj_id = measobjid[0].show
                logger.info("A4_measurement_id: measObjectId {}".format(meas_obj_id))
                return meas_obj_id
    raise Exception("A4_measurement_id: measObjectId not found")


def get_measurement_id(packet, rsrp_value, ssb_freq, event_type, time_to_trigger):
    """
    Read pdml file and find A4 measurement id inside RRC Reconfiguration message.
    A4 measurement id is needed for handover scenarios.
    """
    measurement_id = None

    report_config_id = find_report_config(packet, event_type, rsrp_value, time_to_trigger)
    meas_obj_id = find_measurament_object_id(packet, ssb_freq)
    paths_of_measId = packet.paths("x2ap/(.*?)/nr-rrc.measIdToAddModList/(.*?)/nr-rrc.measId")
    for path in paths_of_measId:
        measIds = packet.xpath(path)
        paths_of_reportConfigId = path + "//..//nr-rrc.reportConfigId"
        paths_of_measObjId = path + "//..//nr-rrc.measObjectId"
        reportConfigIds = packet.xpath(paths_of_reportConfigId)
        measObjId = packet.xpath(paths_of_measObjId)
        for meas_id, config_id in zip(measObjId, reportConfigIds):
            if meas_id.show == meas_obj_id and config_id.show == report_config_id:
                measurement_id = measIds[0].show
                logger.console("measurement_id is: {}".format(measurement_id))
                break
        if measurement_id is not None:
            break
    if measurement_id is None:
        raise Exception("{} measurement id could not be found!!!".format(event_type))
    return measurement_id


def get_packets_based_on_message(packet_list, message):
    pdml_log_entries = []
    for packet in packet_list:
        for field_value in packet.findall(message['field_name']):
            if getattr(field_value, message['attrib_name']) == message['attrib_value']:
                if packet not in pdml_log_entries:
                    if message['not_contain']:
                        regex = re.compile(".*{}.*".format(message['not_contain']))
                        match = list(filter(regex.match, str(packet).splitlines()))
                        if not match:
                            pdml_log_entries.append(packet)
                    else:
                        pdml_log_entries.append(packet)
    return pdml_log_entries


def verify_measurement_report(packet, target_pci, measurement_id):
    measurementReport = packet.xpath("x2ap//..//nr-rrc.measurementReport_element//..//nr-rrc.measId")[0].show
    target_physCellId = packet.xpath("x2ap//..//nr-rrc.measResultNeighCells//nr-rrc.physCellId")[0].show
    serving_physCellId = packet.xpath("x2ap//..//nr-rrc.servCellId//..//nr-rrc.physCellId")[0].show
    if target_physCellId == str(target_pci) and measurementReport == measurement_id:
        logger.info(
                     "verify_handover: Successful. Measurement_Id = {} \
                      Target cell physCellId = {} \
                      server_cell = {}".format(measurement_id, target_physCellId, serving_physCellId))
        return
    raise Exception('Measurement report not found measurement_id {} for target cell {}.'.format(measurement_id,
                                                                                                target_pci))


def meas_id_related_to_freq(packet, freq_rsrsp_values, event_type, time_to_trigger):
    freq_list = [item[0] for item in freq_rsrsp_values]
    rsrp_values = [item[1] for item in freq_rsrsp_values]
    meas_ids = {}
    for freq, rsrp in zip(freq_list, rsrp_values):
        meas_id = get_measurement_id(packet, rsrp, freq, event_type, time_to_trigger)
        meas_ids[freq] = meas_id
    logger.info('meas_id {}'.format(meas_ids))
    return meas_ids


def get_regex_date(result, parameter):
    string = ''.join(result)
    values = re.findall(r'{}\:\s(\d+)'.format(parameter), string)
    return values


def get_packet_time(packet):
    """
    Returns relative time of the given packet with 2 digits precision
    """
    string = str(packet).splitlines()
    frame = get_frame_info(string)
    regex = re.compile(".*frame.time_relative.*")
    time_line = list(filter(regex.match, frame))
    time = re.search(r'(?<=show=")[0-9]+\.[0-9]{4}', time_line[0])
    return float(time.group(0))


def get_frame_info(xml):
    in_frame = False
    for line in xml:
        if "<frame showname" in line:
            line = line + "\n"
            frame = [line]
            in_frame = True
            continue
        if in_frame:
            line = line + "\n"
            frame.append(line)
            if "</frame" in line:
                return frame


def get_ip_info(xml):
    in_frame = False
    for line in xml:
        if "<ip showname" in line:
            line = line + "\n"
            frame = [line]
            in_frame = True
            continue
        if in_frame:
            line = line + "\n"
            frame.append(line)
            if "</ip" in line:
                return frame


def check_validation_date_for_meas_ids(result, param_name, meas_ids=None, max_number=None):
    param_value = get_regex_date(result, param_name)
    output = collections.Counter(param_value)
    logger.info('{} {}'.format(param_name, output))
    if param_name == 'measIdToAddModList' or param_name == 'measIdToRemoveList':
        all_meas_num = list(output.values())[0]
        assert all_meas_num == int(max_number), 'There is a missing max number of retry. Should be {} is {}'.format(
            max_number, all_meas_num)
    if param_name == 'measId' or param_name == 'MeasId':
        all_meas_ids = output.keys()
        meas_id_list = set([id for id in meas_ids if id in all_meas_ids])
        assert meas_id_list == set(meas_ids), 'There is a missing {} in {}'.format(meas_ids, all_meas_ids)


