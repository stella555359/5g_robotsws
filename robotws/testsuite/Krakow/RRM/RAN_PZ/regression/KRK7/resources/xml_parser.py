def check_validation_date_for_freq_and_meas_gap(result, param_name, values, max_number=None):
    if len(result) == int(max_number):
        if values:
            for out in result:
                if [freq for freq in values if freq not in out.get(param_name, None)]:
                    raise Exception('{} should contain {} but there is {}'.format(
                        param_name, values, out.get(param_name, None)))
            return
        else:
            for out in result:
                if out.get(param_name, None):
                    raise Exception('{} should contain {} but there is {}'.format(
                        param_name, values, out[param_name]))
            return
    raise Exception('There should be {} for {} but is {}'.format(max_number, param_name, len(result)))


