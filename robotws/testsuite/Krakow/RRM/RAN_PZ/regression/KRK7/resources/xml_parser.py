def has_rrc_reconfiguration_meas_id_removed(packet, measIds, event_to_remove):
    removed_measIds = []
    event_to_remove = "event{}".format(event_to_remove)
    to_remove_measIds = [measId['measId'] for measId in measIds if measId['eventType'] == event_to_remove]

    paths_of_removed_measIds = packet.\
        paths("x2ap/(.*?)/nr-rrc.measIdToRemoveList/(.*?)/nr-rrc.MeasId")

    for path in paths_of_removed_measIds:
        measId = packet.xpath(path)[0]
        removed_measIds.append(measId.show)

    for to_remove in to_remove_measIds:
        if to_remove not in removed_measIds:
            raise Exception('measId = {} not removed! All measId was {} and removed measIds are {}'
                            .format(to_remove, measIds, removed_measIds))


