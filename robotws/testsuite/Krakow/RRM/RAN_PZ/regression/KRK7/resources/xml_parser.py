def get_entry_source_and_destination(packet):
    """
    Returns relative time of the given packet with 2 digits precision
    """
    pkg_info = {}
    string = str(packet).splitlines()
    frame = get_ip_info(string)
    regex = re.compile(".*Internet Protocol Version.*")
    line = list(filter(regex.match, frame))
    src_dest = re.search(r'Src\:\s(?P<source>[\d\.]+),\sDst\:\s(?P<destination>[\d\.]+)', line[0])
    pkg_info['source'] = src_dest.group('source')
    pkg_info['destination'] = src_dest.group('destination')
    return pkg_info


