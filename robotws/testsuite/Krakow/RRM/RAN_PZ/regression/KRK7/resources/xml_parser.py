def verify_time_of_occurence(packet_list, retry_timer):
    message = {
        'field_name': 'x2ap.SgNBAdditionRequestAcknowledge_element',
        'attrib_name': 'showname',
        'attrib_value': 'SgNBAdditionRequestAcknowledge',
        'not_contain': None,
    }
    addition_request_acknowledge_time = get_time_packet_occured(packet_list=packet_list, message=message)

    message = {
        'field_name': 'x2ap.SgNBModificationConfirm_element',
        'attrib_name': 'showname',
        'attrib_value': 'SgNBModificationConfirm',
        'not_contain': None,
    }
    modification_confirm_times = get_time_packet_occured(packet_list=packet_list, message=message)

    message = {
        'field_name': 'x2ap.SgNBModificationRequired_element',
        'attrib_name': 'showname',
        'attrib_value': 'SgNBModificationRequired',
        'not_contain': 'nr-rrc.drx_Config',
    }
    require_times = get_time_packet_occured(packet_list=packet_list, message=message)

    addition_request_acknowledge_time = addition_request_acknowledge_time[-1]
    require_times = require_times[::2]
    modification_confirm_times = modification_confirm_times[3::3]

    print('SgNBAdditionRequestAcknowledge times {}'.format(addition_request_acknowledge_time))
    print('SgNBModificationConfirm times {}'.format(modification_confirm_times))
    print('SgNBModificationRequired times {}'.format(require_times))

    for index, items in enumerate(require_times, 1):
        if index == 1:
            first_timer = items - addition_request_acknowledge_time
            assert int(first_timer) == int(retry_timer), '{} timer raise after {} insted of {}'.format(
                index, first_timer, retry_timer)
        else:
            difference = items - modification_confirm_times[index-2]
            assert int(difference) == int(retry_timer), '{} timer raise after {} insted of {}. {} {}'.format(
                index, retry_timer, difference, items, modification_confirm_times[index-2])


def verify_supervision_timer_of_occurence(time_of_occurent, time_of_missing, supervision_timer):
    if not isinstance(time_of_occurent, list):
        time_of_occurent = [time_of_occurent]

    if not isinstance(time_of_missing, list):
        time_of_missing = [time_of_missing]

    for occur, missing in zip(time_of_occurent, time_of_missing):
        difference = missing - occur
        assert int(difference) == int(supervision_timer)/1000, \
            'supervision_timer raise after {} insted of {}.'.format(difference, int(supervision_timer)/1000)
    logger.console('Supervision_timer correct')


