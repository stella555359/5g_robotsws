    def _log_to_file(self, log, console=False):
        if log.count("step:"):
            self.log_f.write(log + "\n")
        else:
            self.log_f.write("    " + log + "\n")
        if console:
            print(log)

    def _parse_filter_file(self, filter_file):
        """
        filter file example:
        [CP1]
        ngap.procedureCode == 14 && ngap.fiveQI == 6
        f1ap.procedureCode == 12 and f1ap.SRBID == 1 and nr-rrc.rat_Type == 0
        ngap.procedureCode == 14 and ngap.id == 72 and ngap.qosFlowIdentifier == 1
        [CP2]
        ngap.procedureCode == 14 and ngap.fiveQI == 6
        (ngap.procedureCode == 14) && (ngap.RedirectionVoiceFallback == 0)
        ((f1ap.fiveGS_TAC == 0) && (nr-rrc.ssbSubcarrierSpacing == 1)) && (f1ap.procedureCode == 1)

        filter support 2 formats:
        format 1: ngap.procedureCode == 29 and ngap.fiveQI == 1
        format 2: (ngap.procedureCode == 29) && (ngap.fiveQI == 1)

        this keyword will return dictionary with key:CP1/CP2/...and value:filters list (convert to format 1)
        """
        self._log_to_file("step: parse filter file")
        filter_dict = {}
        with open(filter_file, 'r') as f:
            for line in f.readlines():
                line = line.strip()
                if line.startswith("#") or len(line) == 0:
                    continue
                # [CPx], like CP1, CP2...
                if line.startswith("[CP") and line.endswith("]"):
                    cp = line[1:-1].upper()
                    if cp not in filter_dict:
                        filter_dict[cp] = []
                # filter, like ngap.procedureCode == 14 && ngap.fiveQI == 6
                # or like (ngap.procedureCode == 14) && (ngap.RedirectionVoiceFallback == 0)
                else:
                    try:
                        filter_format1 = re.sub(r"\s*&&\s*", " and ", line).replace("(", "").replace(")", "")
                        filter_dict[cp].append(filter_format1)
                        self._log_to_file("debug: {} filter: {}".format(cp, line))
                        self._log_to_file("debug: {} filter after conversion: {}".format(cp, filter_format1))
                    except UnboundLocalError:  # lines in the beginning are not CP block
                        pass
        self._log_to_file("debug: get filter_dict = {}".format(filter_dict))
        if len(filter_dict) == 0:
            raise Exception("no filter in {}".format(filter_file))
        for cp in filter_dict.keys():
            if len(filter_dict[cp]) == 0:
                raise Exception("no filter in [{}] of {}".format(cp, filter_file))
        return filter_dict

    def _create_a2a_ini(self, wireshark_txt_name):
        a2a_ini_content = """
        [Global]
        LOGDIR:
        WIRESHARKLOG_TAG_1:{}
        DOMAIN: Default

        [WiresharkLog_1 CP_1]
        #5:paradigm meet
        CHECK_TYPE: 5
        PARADIGM: ./wireshark.pdm
        REPEAT_NUM: 1
        """.format(wireshark_txt_name)
        a2a_ini_content_list = [line.strip() for line in a2a_ini_content.strip().splitlines()]
        a2a_ini_content = "\n".join(a2a_ini_content_list)
        with open(os.path.join(self.output_dir, "a2a.ini"), "w") as f:
            f.write(a2a_ini_content)
        return os.path.join(self.output_dir, "a2a.ini")

    def _create_empty_wireshark_pdm(self):
        with open(os.path.join(self.output_dir, "wireshark.pdm"), "w") as f:
            f.write("")

    def _generate_wireshark_decode_file(self, wireshark_txt_with_path):
        a2a_decode_file = wireshark_txt_with_path + ".a2a_decode"
        wireshark_log_dir, wireshark_txt_name = os.path.split(wireshark_txt_with_path)
        a2a_ini = self._create_a2a_ini(wireshark_txt_name)
        if not os.path.exists(a2a_decode_file) or self.re_decode:
            self._log_to_file("step: generating wireshark decode file: {}".format(a2a_decode_file), console=True)
            self._create_empty_wireshark_pdm()
            try:
                self.a2a_obj.check_log_with_au2anlysis(a2a_ini, "w", save_log_directory=wireshark_log_dir)
            except Exception as e:
                pass
            if not os.path.exists(a2a_decode_file):
                raise Exception("fail to generate {}".format(a2a_decode_file))
        else:
            self._log_to_file("step: get {}".format(a2a_decode_file), console=True)
        return a2a_decode_file

    def _convert_filter_to_regex(self, filter):
        if filter.count("itf_") or filter.count("UlCell_"):
            return self._convert_filter_to_regex_syscom(filter)
        else:
            return self._convert_filter_to_regex_non_syscom(filter)

    def _convert_filter_to_regex_non_syscom(self, filter):
        """
        format conversion like:
        f1ap.procedureCode == 12 and nr-rrc.rat_Type == 0 ==> (f1ap.*procedureCode=12)|(f1ap.*rat-Type=0)

        special handling
        *) remove middle fields, for example:
               nr-rrc.measTriggerQuantity.rsrp == 34 ==> nr-rrc.rsrp == 34
               because measTriggerQuantity not in a2a decode file
        *) insert condition (without = ) into filter regular expression
        *) nr-rrc and nas_5gs.mm.req_type == 1 ==> f1ap.req_type == 1
        *) nr-rrc. ==> f1ap.|x2ap.|ngap.
        *) different key between filter and txt, see key_mapping
        *) xnap.serving_PLMN == 13:41:20 ==> xnap.serving_PLMN == 134120
        *) xnap.TAC == 100 ==> xnap.TAC == 0x000064
        *) procedureCode ==> procedureCode|procedure_code
        *) nr-rrc.logicalChannelSR_Mask == 1 ==> nr-rrc.logicalChannelSR_Mask == True (0:False, 1:True)
        *) nokiaxnap ==> xnap, nokiaf1ap==> f1ap
        *) nokiaxnap.TransportLayerAddressIPv4 == 10.0.1.24 ==> xnap.TransportLayerAddress (IPv4) == 10.0.1.24
        *) nokiaf1ap.transportLayerAddressIPv4 == xx ==> f1ap.IPv4 transportLayerAddress == xx
        """
        filer_regex_str = ""
        filer_regex_list = []
        # convert == to = and make sure only one space before and after it
        filter = re.sub(r"\s*==\s*", " = ", filter)

        # key mapping from wireshark filter to wireshark txt
        key_mapping = [("nokiaxnap", "xnap"),
                       ("nokiaf1ap", "f1ap"),
                       ("req_type", "Request type"),
                       ("mm_sd", r"Slice differentiator \(SD\)"),
                       ("pdu_session_id", "PDU session identity"),
                       ("message_type", "Message type"),
                       ("NR-Cell-Identity", "nr-CI"),
                       ("TransportLayerAddressIPv4", r"TransportLayerAddress \(IPv4\)"),
                       ("TransportLayerAddressIPv6", r"TransportLayerAddress \(IPv6\)"),
                       ("transportLayerAddressIPv4", "IPv4 transportLayerAddress"),
                       ("transportLayerAddressIPv6", "IPv6 transportLayerAddress"),
                       ]
        for key in key_mapping:
            filter = filter.replace(key[0], key[1])

        # find message block for example
        # nr-rrc.rrcReconfiguration_element  ==> rrcReconfiguration
        # ngap.PDUSessionResourceModifyListModReq  ==> PDUSessionResourceModifyListModReq
        # nr-rrc and nas_5gs.mm.req_type == 1 ==》 nr-rrc
        message_block_name = ""
        for each_condition in filter.split(" and "):
            each_condition = each_condition.strip()
            if each_condition.count("=") == 0:
                message_block_name = each_condition.split(".")[-1].replace("_element", "")
                break

        # convert each condition like key=value
        for each_condition in filter.split(" and "):
            each_condition = each_condition.strip()
            if each_condition.count("="):
                key, value = each_condition.split(" = ")
                key_new, value_new = key, value
                # (1) convert key
                # remove middle fields and if no message_block_name
                if len(message_block_name) == 0:
                    key_new = "{}.{}".format(key.split(".")[0], key.split(".")[-1])
                # nr-rrc and nas_5gs.mm.req_type == 1 ==> f1ap.req_type == 1
                elif message_block_name == "nr-rrc":
                    key_new = "f1ap." + key.split(".")[-1]
                elif message_block_name.count("nsetap"):
                    pass
                # remove middle fields and add message_block_name if specified
                else:
                    key_new = "{}.{}.{}".format(key.split(".")[0],
                                                message_block_name,
                                                key.split(".")[-1])
                if filter.count("nsetap"):
                    # nr-rrc.rsType == 0 and nsetapx => nsetap.*rsType = 0
                    key_new = key_new.replace("nr-rrc", "(nsetap.rrcReconfiguration)")
                else:
                    # nr-rrc. ==> f1ap.|x2ap.|ngap.|xnap.
                    key_new = key_new.replace("nr-rrc", "(f1ap|x2ap|ngap|xnap)")
                # procedureCode ==> procedureCode|procedure_code
                key_new = key_new.replace("procedureCode", "(procedureCode|procedure_code)")
                # common conversion: _ or - > (_|-)
                if key_new.count("_"):
                    key_new = key_new.replace("_", "(_|-)")
                elif key_new.count("-"):
                    key_new = key_new.replace("-", "(_|-)")
                # common conversion: . => .*\.
                key_new = key_new.replace(".", r".*\.")
                # gnb-ID: 000008 [bit length 22, 2 LSB pad bits, 0000 0000  0000 0000  0000 10.. decimal value 2]
                # add _pre to get the first value 000008
                # without _pre, will get bit length 22, 2 LSB pad bits, 0000 0000  0000 0000  0000 10.. decimal value 2
                key_new = key_new + "(|_pre)"
                # nsetapx and nrppa.measurementQuantitiesValue == 6 => nsetap.*nrppa.*measurementQuantitiesValue = 6
                if filter.count("nsetap") and each_condition.count("=") and not key_new.count("nsetap"):
                    key_new = r"nsetap.*\.{}".format(key_new)
                # nsetapx.traceActivationType == 0 ==> nsetap.traceActivationType == 0
                if key_new.count("nsetapx"):
                    key_new = key_new.replace("nsetapx", "nsetap")

                # (2) convert value
                # xnap.serving_PLMN == 13:41:20 ==> xnap.serving_PLMN == 134120
                # nokiaf1ap.SelectedBandCombinationIndex == 00:01 ==》 nokiaf1ap.SelectedBandCombinationIndex == 0001
                # exception: xnap.TransportLayerAddressIPv6 == fc00::172:18:6:24
                if not key.count("IPv6"):
                    value_new = value_new.replace(":", "")
                # xnap.TAC == 100 ==> xnap.TAC == 0x000064
                if key.lower().endswith("tac"):
                    value_new = "0x{}".format(hex(int(value_new))[2:].zfill(6))
                # common convertion: value 0 -> 0|False, 1-> 1|True
                # nr-rrc.logicalChannelSR_Mask == 1 ==> nr-rrc.logicalChannelSR_Mask == True
                if value_new == "0":
                    value_new = "(0|False)"
                elif value_new == "1":
                    value_new = "(1|True)"
                # nrppa.MeasuredResultsValue == 5 ==》 MeasuredResultsValue: choice-Extension (5): id-ResultSS-RSRP
                if key.endswith("MeasuredResultsValue"):
                    value_new = r".*\({}\).*".format(value)

                # (3) filter regex
                each_condition_new = key_new + " = " + value_new
                if len(filer_regex_str):
                    filer_regex_str = filer_regex_str + "|"
                filer_regex_str = filer_regex_str + "({})".format(each_condition_new)
                filer_regex_list.append(each_condition_new)

        # only include one element, for example: nr-rrc.rrcReestablishmentComplete_element
        if filter.count("=") == 0 and len(message_block_name):
            filer_regex_str = message_block_name
            filer_regex_list = [message_block_name]
        return filer_regex_str, filer_regex_list

    def _convert_filter_to_regex_syscom(self, filter):
        """
        not support:
            Length = xxx
            field without value
        """
        filer_regex_str = ""
        filer_regex_list = []
        # convert == to = and make sure only one space before and after it
        filter = re.sub(r"\s*==\s*", " = ", filter)
        # convert each condition like key=value
        for each_condition in filter.split(" and "):
            each_condition = each_condition.strip()
            if each_condition.count(" = "):
                key, value = each_condition.split(" = ")
                if key == "Length":
                    print("[\033[0;31;40mWARN\033[0m] pdm tool can't support this filter: {}".format(each_condition))
                    print("[\033[0;31;40mWARN\033[0m] please search it in a2a_decode file by yourself")

                # itf_l2_ps_pusch_PuschConfig.minOfPmax_item = > itf_l2_ps_pusch_PuschConfig\)\.minOfPmax .*
                # itf_l2_ps_pucch_PucchConfigCommon.deltaPriList_item =>
                # itf_l2_ps_pucch_PucchConfigCommon.deltaPriList_item.*
                elif key.endswith("_item"):
                    each_condition_new = each_condition.replace(".", r"\)*.*\.").replace("_item", "( |_item).*")

                # itf_l2_ps_CellConfigParam_t.sCellIndex = > itf_l2_ps_CellConfigParam_t\)\.sCellIndex .*
                else:
                    new_key = key.replace(".", r"\)*\.") + " .*"
                    each_condition_new = new_key + " = " + value
            else:
                raise Exception("don't use simple filter: {}, please select field who has value".format(each_condition))
                # each_condition_new = "{}(|\)) = None".format(each_condition)
            if len(filer_regex_str):
                filer_regex_str = filer_regex_str + "|"
            filer_regex_str = filer_regex_str + "({})".format(each_condition_new)
            filer_regex_list.append(each_condition_new)
        return filer_regex_str, filer_regex_list

    def _parse_search_result(self, result):
        """
        parse strings like:
        frame_number = 1347
        frame_number = 1358
        ethernet.ipv6.sctp.f1ap.F1AP-PDU.initiatingMessage.value.ULRRCMessageTransfer.protocolIEs.Item 3.
        ProtocolIE-Field.value.RRCContainer.5   ).NR Radio Resource Control (RRC) protocol.UL-DCCH-Message.
        message.c1 = 5
        ethernet.ipv6.sctp.f1ap.F1AP-PDU.initiatingMessage.procedureCode = 13
        frame_number = 1366
        ethernet.ipv6.sctp.f1ap.F1AP-PDU.initiatingMessage.procedureCode = 13

        return dictionary whose key frame_number, and value is lines between two frame_number.
        if value is empty, remove the key from dictionary.
        """
        frame_dict = {}
        frame_dict_out = {}
        for line in result.splitlines():
            if line.startswith("frame_number"):
                frame_number = int(line.split("=")[-1].strip())
                if frame_number not in frame_dict:
                    frame_dict[frame_number] = []
            else:
                frame_dict[frame_number].append(line)
        for frame_number in frame_dict.keys():
            if len(frame_dict[frame_number]):
                self._log_to_file("debug: frame_number = {}".format(frame_number))
                frame_dict[frame_number].sort()
                frame_dict_out[frame_number] = "\n".join(frame_dict[frame_number])
                self._log_to_file("debug: {}".format(frame_dict_out[frame_number]))
        return frame_dict_out

    def _convert_filter_to_pdm(self, wireshark_decode_file, filter, cp):
        frame_numbers_found = []
        # grep all lines match the filter
        regex_str, regex_list = self._convert_filter_to_regex(filter)
        self._log_to_file("debug: regex is {}".format(regex_str))
        decode_file_content = os_obj.get_file(wireshark_decode_file)
        lines_str = str_obj.get_lines_matching_regexp(decode_file_content, "(?i)frame_number|" + regex_str,
                                                      partial_match=True)
        lines_str = re.sub(r"nsetap\[\d+\]", "nsetap", lines_str)
        frame_dict = self._parse_search_result(lines_str)

        # only frame which include all the conditions in the filter should be expected
        for frame_number in frame_dict.keys():
            frame_pdm = frame_dict[frame_number]
            find_flag = True
            for each_condition in regex_list:
                if re.search(each_condition, frame_pdm, re.I) is None:
                    self._log_to_file("debug: fail to find {} in frame {}".format(each_condition, frame_number))
                    find_flag = False
                    break
            if find_flag:
                frame_numbers_found.append(frame_number)
        if len(frame_numbers_found):
            select_done = False
            for frame_no in frame_numbers_found:
                if frame_no > self.frame_number_select:
                    select_done = True
                    self.frame_number_select = frame_no
                    out = frame_dict[frame_no].splitlines()
                    break
            if select_done:
                self._log_to_file("debug: {} filter: {}, matched frame numbers in wireshark log: {}, "
                                  "select frame {} for pdm".format(cp,
                                                                   filter,
                                                                   frame_numbers_found,
                                                                   frame_no))
                return out
            else:
                print(os_obj.grep_file("auto_pdm_debug_log.txt", "select frame"))
                self._log_to_file("debug: {} filter: {}, matched frame numbers in wireshark log: {}".format(
                    cp,
                    filter,
                    frame_numbers_found), console=True)
                raise Exception("message sequence is wrong")
        else:
            raise Exception("fail to find filter:{}\n"
                            "step1: make sure it exists in wireshark pcap -- filter it with wireshark GUI.\n"
                            "step2: make sure it exists in wireshark txt -- search frame number got from step1 "
                            "in wireshark txt.\n"
                            "step3: if no problem in step1 and step2, "
                            "ask zhangyin for help, can't find the filter's regex {} in decode file.".format(filter,
                                                                                                             regex_str))

    def _get_frame_head(self, filter, pdm_entry):
        if pdm_entry.count("nsetap"):
            protocol = "nsetap"
        elif filter.count("nr-rrc") and pdm_entry.count("x2ap"):
            protocol = "x2ap"
        elif filter.count("nr-rrc") and pdm_entry.count("f1ap"):
            protocol = "f1ap"
        elif filter.count("nr-rrc") and pdm_entry.count("ngap"):
            protocol = "ngap"
        elif filter.count("nr-rrc") and pdm_entry.count("xnap"):
            protocol = "xnap"
        elif filter.count("nokiaf1ap"):
            protocol = "f1ap"
        elif filter.count("nokiaxnap"):
            protocol = "xnap"
        elif filter.count("nrppa"):
            protocol = "ngap"
        elif filter.count("itf_") or filter.count("UlCell_"):
            protocol = "syscom"
        else:
            protocol = filter.split(".")[0]
        # print("pdm_entry is {}".format(pdm_entry))
        # print("protocol is {}".format(protocol))
        if protocol not in pdm_entry:
            raise Exception("fail to find {} in {}, ask zhangyin for help".format(protocol, pdm_entry))
        return pdm_entry.partition(protocol)[0] + protocol

    def generate_wireshark_pdm(self, wireshark_txt_with_path, filter_file):
        # create output dir
        os_obj.remove_directory(self.output_dir, True)
        os_obj.create_directory(self.output_dir)
        # copy wireshark txt to input dir and pcap to output
        self.wireshark_txt = os.path.join(os.path.abspath(self.input_dir), os.path.basename(wireshark_txt_with_path))
        os_obj.copy_file(wireshark_txt_with_path, self.wireshark_txt)
        try:
            os_obj.copy_file(wireshark_txt_with_path.replace(".txt", ".pcap"), self.output_dir)
        except Exception:
            pass

        # parse filter file
        filter_dict = self._parse_filter_file(filter_file)
        # generate wireshark a2a decode file
        wireshark_decode_file = self._generate_wireshark_decode_file(self.wireshark_txt)
        # search filter in a2a decode file and write pdm file
        with open(os.path.join(self.output_dir, "wireshark.pdm"), "w") as f:
            self._log_to_file("step: write pdm head")
            pdm_head = "[Global]\nRELATION: {}\nBlOCKSIZE: -1".format("&".join(filter_dict.keys()))
            f.write(pdm_head + "\n\n")
            self._log_to_file("{}".format("\n    ".join(pdm_head.split("\n"))))

            for cp in filter_dict.keys():
                self.frame_number_select = 0
                f.write("[{}]\n".format(cp))
                self._log_to_file("step: handling {}".format(cp), console=True)
                for filter in filter_dict[cp]:
                    self._log_to_file("step: converting filter: {}".format(filter), console=True)
                    f.write("# filter: {}\n".format(filter))
                    pdm_entries = self._convert_filter_to_pdm(wireshark_decode_file, filter, cp)
                    frame_head = self._get_frame_head(filter, pdm_entries[0])
                    self._log_to_file("step: write frame head: \n    {}".format(frame_head))
                    f.write(frame_head + "\n")
                    self._log_to_file("step: write pdm entries: \n    {}".format("\n    ".join(pdm_entries)))
                    for entry in pdm_entries:
                        f.write("    {}\n".format(entry))
                    f.write("\n")

        print("[\033[0;33;40mINFO\033[0m] output/wireshark.pdm is auto generated")
        print("[\033[0;33;40mINFO\033[0m] output/a2a.ini is auto generated")

    def verify_wireshark_pdm(self):
        # self._log_to_file("\nverifying wireshark.pdm by a2a tool", console=True)
        a2a_ini = os.path.join(self.output_dir, "a2a.ini")
        wireshark_log_dir = os.path.abspath(self.input_dir)
        try:
            self.a2a_obj.check_log_with_au2anlysis(a2a_ini, "w", save_log_directory=wireshark_log_dir)
            self._log_to_file("[\033[0;33;40mINFO\033[0m] output/wireshark.pdm is matched with wireshark txt",
                              console=True)
        except Exception:
            self._log_to_file("[\033[31mERROR\033[0m] output/wireshark.pdm is not matched with wireshark txt",
                              console=True)
            self.log_f.close()
            print(os_obj.grep_file("auto_pdm_debug_log.txt", "select frame"))


