# -*- coding: utf-8 -*-
import sys
import logging
import os
import shutil
from robot.libraries.BuiltIn import BuiltIn

from testsuite.Nanjing.OAM.Resources.python.DevNJ_ssh import (
    SshClient,
)

if sys.version_info.major == 3:
    import subprocess as commands
else:
    import commands

epcsim_pkg = "esimmode_WTS_2221833.19_4.0.14006_core2.tar.bz2"


class EPCSimCfg(object):
    def __init__(self):
        pass

    def prepare_epcsim(self, epcsim_dir):
        # download epcsim from load server
        client = SshClient("10.66.11.28", "scpadm", "M%ACTfVV&U!k3qqL#1r4")
        client.get("/home/scpadm/SPACE/COMMON/tools/{}".format(epcsim_pkg), epcsim_pkg)

        os.system("sudo rm -rf {0} && sudo mkdir -p {0}".format(epcsim_dir))
        os.system("sudo tar jxf {} -C {}".format(epcsim_pkg, epcsim_dir))
        os.system("sudo chown -R ute.ute {}".format(epcsim_dir))

    def generate_cfg(self, epcsim_dir):
        if not os.path.exists(os.path.join(epcsim_dir, "egate")):
            self.prepare_epcsim(epcsim_dir)

        file = os.path.join(epcsim_dir, "epcsim_autogenerated.cfg")
        if os.path.exists(file):
            os.remove(file)
        dir_path = os.path.dirname(os.path.realpath(__file__))
        shutil.copy("{}/../robot/configuration_file/epcsim.cfg".format(dir_path), file)

        _tl = BuiltIn().get_variable_value("${tl}")

        # replace parameters
        parameters = [
            {
                "key": "DAEMON_PORT",
                "value": _tl.core.edaemon_port,
            },
            {
                "key": "MCC",
                "value": _tl.core.mcc,
            },
            {
                "key": "MNC",
                "value": str(_tl.core.mnc).zfill(2),
            },
            {
                "key": "TAC",
                "value": _tl.core.tac,
            },
            {
                "key": "ENB_ADDR",
                "value": _tl.enbs[0].x2_link_addr.v4,
            },
            {
                "key": "EPC_ADDR",
                "value": _tl.core.mme_ip,
            },
        ]
        # epcsim_config, example
        # epcsim_config = [
        #     {
        #         'key': 'PGW_ADDR',
        #         'value': '27.168.1.200/24',
        #     },
        #     {
        #         'key': 'SEC_KEY',
        #         'value': '11111111111111111111111111111111',
        #     },
        #     {
        #         'key': 'OPC_KEY',
        #         'value': '11111111111111111111111111111111',
        #     },
        #     # Support up to 10 UEs. from IMSI_1 ~ IMSI_10, UE_IP_1 ~ UE_IP_10
        #     {
        #         'key': 'IMSI_1',
        #         'value': '460:06:4100000010',
        #     },
        #     {
        #         'key': 'UE_IP_1',
        #         'value': '27.168.1.10',
        #     },
        #     {
        #         'key': 'IMSI_2',
        #         'value': '460:06:4100000011',
        #     },
        #     {
        #         'key': 'UE_IP_2',
        #         'value': '27.168.1.11',
        #     },
        # ]
        if hasattr(_tl, "epcsim_config"):
            parameters.extend(_tl.epcsim_config)

        for item in parameters:
            key = item["key"]
            value = item["value"]
            cmd = r"sed -i 's/^set\s*{0}=.*$/set {0}=\"{1}\"/g' {2}".format(
                key, value, file
            )
            ret_code, output = commands.getstatusoutput(cmd)
            if ret_code != 0:
                raise Exception(
                    "Fail to modify. Output message for command {} is {}".format(
                        cmd, output
                    )
                )
            else:
                logging.debug(
                    "Modify parameter {} value to {} successfully".format(key, value)
                )

        return "epcsim_autogenerated.cfg"


__all__ = ["EPCSimCfg"]
