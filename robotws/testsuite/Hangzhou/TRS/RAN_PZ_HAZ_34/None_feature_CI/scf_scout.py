__all__ = ["ScfScout"]


class ScfScout(scout):
    def __init__(self):
        super(ScfScout, self).__init__()
        self._url_template = None

    def _init_url_template(self, alias="default"):
        self._url_template = (
            "https://scout.nsn-rdnet.net/api/v1/"
            "{url_part}apitoken=8516481f-f768-4ae0-8841-d8ca405ed3de"
        )
        # https://scout.nsn-rdnet.net/api/v1/{url_part}apitoken=xxxxx
        return self._url_template

    def get_testline_id(self, tl):
        oam_ip = tl.gnbs[0].dus[0].f1_m_ip_addr or tl.gnbs[0].cu.oam_http_connection_details.addr
        url_template = (
            "https://scout.nsn-rdnet.net/api/v1/testlines/"
            "?filter%5Bmplane%5D%5Bicontains%5D={ip}"
            "&page%5Blimit%5D=25&page%5Boffset%5D=0"
            "&apitoken=8516481f-f768-4ae0-8841-d8ca405ed3de")
        res = requests.get(url_template.format(ip=oam_ip))
        data = json.loads(res.text)["data"]
        if not data:
            raise AttributeError("{} TL not found on Scout".format(oam_ip))
        return data[0]["attributes"]["name"]

    @staticmethod
    def generate_feature_id(feature_list):
        ids = {}
        for feature in feature_list.split(","):
            for key in FEATURE_DICT:
                if key == feature:
                    ids[FEATURE_DICT[key]] = key
                    break
        return ids

    @property
    def url_template(self):
        return self._url_template if self._url_template else self._init_url_template()

    def get_fas_id(self, scf_id, timeout=30, alias="default", wait_until_finished=True):
        alias = self._try_to_string(alias, "alias")
        api = self.store.get_alias_value(alias)
        start_time = datetime.now()
        timeout_time = start_time + timedelta(seconds=int(timeout))
        url = self.url_template.format(
            url_part="scfs_analysis/?filter[scf]={scf_id}&include=errors&".format(
                scf_id=scf_id
            )
        )

        while True:
            if datetime.now() > timeout_time:
                raise Exception("Get SCF analyze id failed.")
            res = api.connection.get(url)
            if res:
                if wait_until_finished:
                    if res[0]["meta"]["status_display"] == "finished":
                        return res[0]["id"]
                else:
                    return res[0]["id"]
            time.sleep(3)

    def check_features(self, feature_list, fas_id, testline, scf_file):
        feature_results = {}
        target_ids = self.generate_feature_id(feature_list.upper())
        check_url = self.url_template.format(
            url_part="fas_entries/?filter[analysis]={fas_id}&page[offset]=0&page[limit]=9999&".format(
                fas_id=fas_id
            )
        )
        results = self._get_feature_results(check_url)
        for result in results:
            id = result["definition"]["id"]
            if id in target_ids:
                feature_results[target_ids[id]] = {
                    "result": result["meta"]["status_display"],
                    "display": result["meta"]["count_summary_display"],
                }
        fas_link_url = "https://scout.nsn-rdnet.net/testlines/{}/scf-analysis-list/{}/fas-details".format(
            testline, fas_id
        )
        enabled_features = {}
        not_app_features = {}
        disabled_features = {}
        for result in feature_results:
            if feature_results[result]["result"] == "enabled":
                enabled_features[result] = feature_results[result]
            elif feature_results[result]["result"] == "not applicable":
                not_app_features[result] = feature_results[result]
            else:
                disabled_features[result] = feature_results[result]
        disable_feature_print = "*** Disabled Fetures ***\n" + "\n".join(
            [
                "{} | {} | {}".format(i, disabled_features[i]["result"], disabled_features[i]["display"])
                for i in disabled_features
            ]
        )
        pass_features_print = "*** Enabled Features ***\n" + ", ".join([i for i in enabled_features])
        not_app_print = "*** Not Applicable Features ***\n" + ", ".join([i for i in not_app_features])
        logging.warning(
            "{} FAS link: {} \n{}\n{}\n{}".format(
                scf_file, fas_link_url, disable_feature_print, pass_features_print, not_app_print
            )
        )
        for result in feature_results:
            if feature_results[result]["result"] not in ["not applicable", "enabled"]:
                raise Exception("Features not all enabled")

    def _get_feature_results(self, url, timeout=30, alias="default"):
        alias = self._try_to_string(alias, "alias")
        api = self.store.get_alias_value(alias)
        start_time = datetime.now()
        timeout_time = start_time + timedelta(seconds=int(timeout))

        while True:
            if datetime.now() > timeout_time:
                raise Exception("Get SCF analyze id failed.")
            res = api.connection.get(url)
            if res:
                return res
            time.sleep(3)

    @staticmethod
    def log_results(scf_results, fas_results):
        pass_scfs = ""
        fail_scfs = ""
        for scf in scf_results:
            scf_result = "Pass" if scf_results[scf] else "Fail"
            fas_result = "Pass" if scf in fas_results and fas_results[scf] else "Fail"
            if scf_results[scf] and scf in fas_results and fas_results[scf]:
                pass_scfs += "{scf} | {scf_result} | {fas_result}\n".format(
                    scf=scf, scf_result=scf_result, fas_result=fas_result
                )
            else:
                fail_scfs += "{scf} | {scf_result} | {fas_result}\n".format(
                    scf=scf, scf_result=scf_result, fas_result=fas_result
                )
        logging.warning("*** Failed SCF ***\nSCF Name | On Air & L3 call | FAS Feature\n{}".format(fail_scfs))
        logging.warning("*** Pass SCF ***\nSCF Name | On Air & L3 call | FAS Feature\n{}".format(pass_scfs))


