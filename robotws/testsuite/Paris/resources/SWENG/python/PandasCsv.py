def single_import_with_auto_install(package):
    try:
        return __import__(package)
    except ImportError:
        # Change to temp directory to prevent spurious file creation in workspace
        original_dir = os.getcwd()
        temp_dir = tempfile.gettempdir()
        try:
            os.chdir(temp_dir)
            pip.main(['install', package])
        finally:
            os.chdir(original_dir)
    return __import__(package)


def import_with_auto_install(packages):
    results = []
    for package in packages:
        results.append(single_import_with_auto_install(package))
    return results


def deep_dict_to_str(value):
    if isinstance(value, dict):
        return str({k: deep_dict_to_str(v) for k, v in value.items()})
    elif isinstance(value, list):
        return tuple(deep_dict_to_str(v) for v in value)
    else:
        return value


class PandasCsv(object):
    """
    == Purpose ==
    Library to load data from a csv file using pandas python lib.

    == Description ==
    This library allows to load data from a csv file using self.pandas_numpy_libs[0].
    Some methods are also implemented to extract AIR TTI or TEXT colum from a l1l2 trace file generated by sherpa.
    The generation of the new content from the columns is stored it to new csv files.
    The content access can be performed by using SQL like queries is use_sql_query is set to True
    or by using pandas treatments available via methods of this class.

    Examples of usage in Roboframework are available in file:
    testsuite/Paris/resources/SWENG/robot/examples/Example.PandasCsv.robot
    """

    df = None
    sql_df = None
    stored_columns = None
    pandas_numpy_libs = None

    def __init__(self):
        if not OsTool.isDryRun():
            self.pandas_numpy_libs = import_with_auto_install(["pandas", "numpy"])

    def get_pandas_numpy_libs(self):
        return self.pandas_numpy_libs

    def setup_reader(self, file_path, delimiter=";", use_sqlquery=True):
        """
        Read a csv file.
        The usage of this method is === MANDATORY === before doing anything on a csv file.

        :param str file_path: file path of the csv file to be analysed
        :return: none
        """
        self.filepath = file_path
        # Loading csv content in a pandas Dataframe
        self.df = self.pandas_numpy_libs[0].read_csv(
            filepath_or_buffer=file_path,
            delimiter=delimiter)
        if use_sqlquery:
            self.conn = connect(':memory:')                  # open DB connection in memory
            self.df.to_sql('l1l2Traces', self.conn)

    def read_sql_df(self, select_stuff, where_stuff=None):
        """
        INTERNAL USAGE
        Perform a sql SELECT operation on a sherpa micro l1l2 Dataframe loaded in memory
        extracting interesting columns with or without WHERE filter.

        :param select_stuff:      the SELECT part of the sql command run on the Dataframe
        :param where_stuff:       the WHERE part of the sql command run on the Dataframe
        :return:                  None
        """
        try:
            if where_stuff:
                self.sql_df = self.pandas_numpy_libs[0].read_sql("{}{}".format(select_stuff, ' ' + where_stuff),
                                                                 self.conn)
            else:
                self.sql_df = self.pandas_numpy_libs[0].read_sql("{}".format(select_stuff), self.conn)
            print("self.sql_df is: {}".format(self.sql_df))
        except Exception as exc:
            print('Read_sql error:\n{},\ntraceback is:\n{}'.format(exc, traceback.format_exc()))

    def split_bygroup(self, by_value='MSGID', list_grp=None):
        """
        INTERNAL USAGE
        Split a dataframe in groups according to a given column values.

        :param by_value:        the column from which the group are generated
        :param list_grp:        the list of groups values included in by_value column
                                the elements in the list MUST BE PRESENT in the by_value column
        :return:                A couple
                                - df_dict: a dict containing the groups values and the generated Dataframe group
                                - list_grp_totreat: the groups values (matching list_grp if this is not None)
        """
        self.df_bygrp = self.sql_df.groupby(by_value)
        list_grp_totreat = self.sql_df[by_value].unique() if not list_grp else list_grp
        df_dict = {}
        for element in list_grp_totreat:
            try:
                grp_df = self.df_bygrp.get_group(element)
                df_dict[element] = grp_df
            except Exception as exc:
                print('Group may be ABSENT! Exception is:\n{},\ntraceback is:\n{}'.format(exc, traceback.format_exc()))
        return df_dict, list_grp_totreat

    def save_tocsv(self, dict_grp, file_nm, separator=None):
        """
        INTERNAL USAGE
        Save a dataframe group to a csv file.

        :param dict_grp:        the dataframe to be saved as csv file
        :param file_nm:         the destination csv filename (NO extension!)
        :return:                the saved file destination path
        """
        dest_path = None
        try:
            myCsv_list = []
            dest_path = "{}/{}.csv".format(
                os.path.dirname(self.filepath),
                file_nm.replace(' ', '_').replace('(', '_').replace(')', '_'))
            if separator:
                dict_grp.to_csv(dest_path, sep=separator)
            else:
                dict_grp.to_csv(dest_path)
            myCsv_list.append(dest_path)
        except Exception as exc:
            print('exception is:\n{},\ntraceback is:\n{}'.format(exc, traceback.format_exc()))
        return dest_path

    def get_splitted_content(self, content_df, filter_column, line_idx):
        """
        INTERNAL USAGE
        Get the content of a column to define new columns names.

        :param content_df:        the dataframe to be treaten
        :param filter_column:     the column to be splitted in new keys+values
        :param line_idx:          the index of the line to be used
        :return:                  the list from which new columns names will be extracted
        """
        line_sample = content_df[filter_column].iloc[line_idx]
        splitted_line = line_sample.split(',')
        # print("Splitted sample:\n{}".format(splitted_line))
        return splitted_line

    def content_treat_for_text(self, content_df, filter_column='TEXT'):
        """
        INTERNAL USAGE
        Extract columns from a TEXT (default value) field and generate a Dataframe.

        :param content_df:        the dataframe to be treaten
        :param filter_column:     the column name which content is transformed in a new dataframe
        :return:                  the new dataframe
        """
        df_res = None
        splitted_line = self.get_splitted_content(content_df, filter_column, 0)
        # Create a new dataframe from series and column heads.
        dict_row_values = dict()
        print("\nHEADS:\n{}".format(content_df.head()))
        for elem in content_df.head():
            if elem != 'TEXT':
                dict_row_values[elem] = []
        dict_row_values.update(
            {elem.split(':')[0]: list() for elem in splitted_line if ':' in elem})
        dict_row_values.update(
            {elem.split('=')[0]: list() for elem in splitted_line if '=' in elem})
        try:
            for iloc_idx in range(len(content_df)):
                tmp_idx = 0
                for elem in content_df.head():
                    if elem != 'TEXT':
                        self._add_element(dict_row_values, elem, content_df.iloc[iloc_idx, tmp_idx])
                        tmp_idx += 1
                splitted_line = self.get_splitted_content(content_df, filter_column, iloc_idx)
                for elem in splitted_line:
                    if ':' in elem:
                        self._add_element(dict_row_values, elem.split(':')[0], elem.split(':')[1])
                    if '=' in elem:
                        self._add_element(dict_row_values, elem.split('=')[0], elem.split('=')[1])
        except Exception as exc:
            print('exception is:\n{},\ntraceback is:\n{}'.format(exc, traceback.format_exc()))
        try:
            # dict cannot be used directly or order of values will bot be preserved
            series_list = list()
            for mykey, my_list in dict_row_values.items():
                series_list.append(self.pandas_numpy_libs[0].Series(my_list, name=mykey))
            df_res = self.pandas_numpy_libs[0].concat(series_list, axis=1)
        except Exception as exc:
            print('exception is:\n{},\ntraceback is:\n{}'.format(exc, traceback.format_exc()))
        return df_res

    def _add_element(self, dict, key, value):
        """
        INTERNAL USAGE
        """
        if key not in dict:
            dict[key] = []
        dict[key].append(value)

    def content_treat_for_airtti(self, column_tosplit, separator, new_names):
        """
        INTERNAL USAGE
        Extract columns from a given field (AIR TTI by default) and generates a new Dataframe.

        :param column_tosplit:        the column to be splitted
        :param separator:             the separator used to split the column
        :param new_names:             a list with the new colums names
        :return:                      the new dataframe
        """
        self.read_sql_df("SELECT TIME,`{}`,MSGID,TEXT FROM l1l2Traces".format(column_tosplit))
        newkeys_list = ['TIME']
        newkeys_list.extend(new_names)
        newkeys_list.extend(['MSGID', 'TEXT'])
        df_res = None
        list1 = list()
        list2 = list()
        list3 = list()
        list4 = list()
        list5 = list()
        try:
            for iloc_idx in range(len(self.sql_df)):
                list1.append(self.sql_df.iloc[iloc_idx, 0])
                to_split = str(self.sql_df.iloc[iloc_idx, 1]).split(separator)
                list2.append(to_split[0])
                list3.append(to_split[1])
                list4.append(self.sql_df.iloc[iloc_idx, 2])
                list5.append(self.sql_df.iloc[iloc_idx, 3])
                serie1 = self.pandas_numpy_libs[0].Series(list1, name=newkeys_list[0])
                serie2 = self.pandas_numpy_libs[0].Series(list2, name=newkeys_list[1])
                serie3 = self.pandas_numpy_libs[0].Series(list3, name=newkeys_list[2])
                serie4 = self.pandas_numpy_libs[0].Series(list4, name=newkeys_list[3])
                serie5 = self.pandas_numpy_libs[0].Series(list5, name=newkeys_list[4])
                df_res = self.pandas_numpy_libs[0].concat([serie1, serie2, serie3, serie4, serie5], axis=1)
        except Exception as exc:
            print('\nCurrent index: {} \nexception is:\n{},\ntraceback is:\n{}'.format(iloc_idx,
                                                                                       exc,
                                                                                       traceback.format_exc()))
        return df_res

    def extract_cvs_files_forcolumn(self, select_columns="TIME,`SHERPA TTI`,`AIR TTI`,MSGID,TEXT",
                                    filter_column='TEXT', by_value='MSGID', list_grp=None,
                                    filter='PrbPollingAllocationReport', csv_sep=None):
        """
        From a given dataframe a groups set is genarated based on differents values of by_value colum.
        It is possible to define a filter string for by_value to reduce dataframe content.
        For each group:
            - Extract columns from a TEXT (default value) field.
            - Generates a dictionary based Dataframe.
            - Each new dataframe a csv file is generated and saved.

        :param select_columns:       SELECT operation to be performed on the source file.
                                     This allows different content for source dataframes
        :param filter_column:        the column to be treaten
        :param by_value:             the column used to generate groups and new csv files based on values
        :param list_grp:             a list of values to generate groups and new csv files
                                     the elements in the list MUST BE PRESENT in the by_value column
        :param filter:               WHERE filter for the SELECT operation to be performed on the source file
        :param csv_sep:              separator for destination csv files
        :return:                     A list of paths for saved csv files
        """
        self.read_sql_df("SELECT {} FROM l1l2Traces".format(select_columns),
                         "WHERE {} LIKE '%{}%'".format(by_value, filter))
        df_dict, list_grp_totreat = self.split_bygroup(by_value, list_grp)
        saved_files = []
        try:
            for elem in list_grp_totreat:
                df_res = self.content_treat_for_text(df_dict[elem])
                self.stored_colums = df_res.columns
                res_save = self.save_tocsv(df_res, elem, csv_sep)
                saved_files.append(res_save)
        except Exception as exc:
            print('exception is:\n{},\ntraceback is:\n{}'.format(exc, traceback.format_exc()))
        return saved_files

    def generate_cvs_file_with_splitted_column(self, column_tosplit='AIR TTI', separator='.',
                                               new_names=['AIR TTI SFN', 'AIR TTI SLOT'], csv_sep=None):
        """
        From a given dataframe a column is replaced by two columns containing its splitted values
        and the content is saved to a new csv file.

        :param column_tosplit:        the column to be splitted
        :param separator:             the separator used to split the column
        :param new_names:             a list with the new colums names
        :param csv_sep:               separator for destination csv files
        :return:                      the path for the saved csv file
        """
        res_save = ""
        df_res = self.content_treat_for_airtti(column_tosplit, separator, new_names)
        try:
            res_save = self.save_tocsv(df_res, "Splitted_AIR_TTI", csv_sep)
        except Exception as exc:
            print('exception is:\n{},\ntraceback is:\n{}'.format(exc, traceback.format_exc()))
        return res_save

    def check_max_for_column(self, column_name):
        """ Check and return the maximum value of a column for a given dataframe
            :param  column_name: event that you want to describe
            :return the maximum value of the specified column
        """
        max_value = self.df[column_name].max()
        return max_value

    def get_columns_with_same_values(self):
        """ Get the list of columns in a dataframe where all the values are the same
            :return: List of columns with the same values
        """
        columns_with_same_values = []
        for column in self.df.columns:
            self.df[column] = self.df[column].apply(deep_dict_to_str)
            if self.df[column].nunique() == 1:
                columns_with_same_values.append(column)
        return columns_with_same_values

    def get_columns_with_long_names(self):
        """ Get the list of columns in a dataframe where name contains at least 2 . (dots)
            :return: List of columns with long names"""
        columns_with_long_names = [column for column in self.df.columns if column.count('.') >= 2]
        return columns_with_long_names

    def check_unique_value_for_column(self, column_name):
        """ Check if a given column has a unique value and return the result and the value
            :param  column_name: Column name to check
            :return: True if the column has a unique value, False otherwise
        """
        self.df[column_name] = self.df[column_name].apply(deep_dict_to_str)
        has_unique_value = self.df[column_name].nunique() == 1
        value = self.df[column_name].iloc[0] if has_unique_value else None
        return has_unique_value, value

    def get_column_values(self, column_name):
        """ Get the list of values of a column in the dataframe
        Args:
            :param  column_name: column to search for values
        Returns:
            :return: List of values of the column
        """
        self.df[column_name] = self.df[column_name].apply(deep_dict_to_str)
        return self.df[column_name].tolist()

    def get_first_column_value(self, column_name):
        """ Get the first valid index and value of a column in the dataframe
        Args:
            :param  column_name: column to search for value
        Returns:
            :return: Index and value of the first valid index
        """
        df = self.df
        df[column_name] = df[column_name].apply(deep_dict_to_str)
        index = df[column_name].first_valid_index()
        value = df[column_name].loc[index]
        return index, value

    def get_number_of_not_empty_cells(self, column_name):
        """ Get the number of not empty cells in a column
        Args:
            :param  column_name: column to search for not empty cells
        Returns:
            :return: Number of not empty cells
        """
        return self.df[column_name].notna().sum()

    def count_values(self, column_name):
        """ Count the occurrences of each different value in a column and return the result as a dictionary
        Args:
            :param  column_name: column to count the values
        Returns:
            :return: Dictionary with the count of each different value
        """
        return self.df[column_name].value_counts().to_dict()
