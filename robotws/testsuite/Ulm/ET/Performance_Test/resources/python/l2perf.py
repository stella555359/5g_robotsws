def mute_external_loggers() -> None:
    """Generated by AI: 2026-03-11 - Mute noisy external TAF loggers and namespaces."""
    # AI: Mute explicit loggers and their parent namespaces so dependency logs stay silent.
    muted_logger_names = [
        "taf.transport",
        "taf.transport.ssh",
        "taf.sbts.oam.coam",
        "taf.sbts.oam.coam.admin",
        "taf.internal.aliasing",
        "taf.internal.aliasing.exceptions",
        "paramiko",
        "paramiko.transport",
        "paramiko.channel",
        "transport",
        "channel",
    ]

    for logger_name in muted_logger_names:
        muted_logger = logging.getLogger(logger_name)
        muted_logger.setLevel(logging.CRITICAL + 1)
        muted_logger.propagate = False


def resolve_l2perf_defaults(lxc, cpu, capu_type, cu_type):
    """Generated by AI: 2026-03-10 - Resolve CAPU-based defaults for l2perf arguments.

    Returns tuple: (resolved_lxc, resolved_cpu).
    """
    defaults = {
        "DEFAULT": {"lxc": "0x1730", "cpu": "sm6-snowfish"},
        "ASOE": {"lxc": "0x1518", "cpu": "sm6-snowfish"},
        "ABIP": {"lxc": r"0x2730%0x2732", "cpu": "sm7-marlin"},
    }

    lxc_was_missing = str(lxc).strip().lower() in ("", "none", "null")
    cpu_was_missing = str(cpu).strip().lower() in ("", "none", "null")
    normalized_capu_type = str(capu_type).strip().upper()
    normalized_cu_type = str(cu_type).strip().upper()

    if normalized_cu_type in ("ASOE", "ASOH"):
        selected_key = normalized_cu_type
    else:
        selected_key = normalized_capu_type

    selected_defaults = defaults.get(selected_key, defaults["DEFAULT"])

    resolved_lxc = selected_defaults["lxc"] if lxc_was_missing else lxc
    resolved_cpu = selected_defaults["cpu"] if cpu_was_missing else cpu

    if lxc_was_missing or cpu_was_missing:
        logger.warning(
            "whenever ENABLE_L2PERF is true, CFG_L2PERF_LXC and CFG_L2PERF_CPU should be set"
        )
        logger.warning("Auto Set L2Perf LXC to %s and CPU to %s", resolved_lxc, resolved_cpu)

    return resolved_lxc, resolved_cpu


def generate_l2_perf_logs_multi_lxc(lxcs, cpu='sm6-snowfish', logpath=None, get_info_timeout=300,
                                    connection=taf_transport_ssh_wrapper.CONST_CORE_ALIAS, timeout=None,
                                    log_to_console=False):
    logger.debug('========== start: generate_l2_perf_logs_multi_lxc ==========')
    bash_helper.clone_repo('git@gitlabe1.ext.net.nokia.com:l2-sw-krk-10/l2perf.git')

    if logpath is None:
        cleanup_folder(f"{L2PERF_PY_PATH}/logs")
        logpath = f"{L2PERF_PY_PATH}/logs"

    tm_st = perf_timer.start()
    # GHC: Modified 2026-02-11 - Added conditional execution based on function return values
    if log_to_console:
        print(f"prepare virtualenv")
    prepare_virtualenv(connection=connection, timeout=timeout)

    if log_to_console:
        print(f"get info")
    if get_info(connection=connection, timeout=get_info_timeout):
        if log_to_console:
            print(f"download")
        if l2perf_download(cpu, connection=connection, timeout=timeout):
            if log_to_console:
                print(f"install")
            if l2perf_install(lxcs, cpu, connection=connection, timeout=timeout):
                if log_to_console:
                    print(f"collect logs")
                collect_logs(lxcs, cpu, logpath=logpath, connection=connection, timeout=timeout)

    try:
        collected_logs = [f"{logpath}/{log}" for log in os.listdir(logpath)]
    except FileNotFoundError:
        logger.error(f"    - collect_logs failed: logpath '{logpath}' not found.")
        collected_logs = []

    logger.debug(f"    collected_logs: {collected_logs}")
    logger.debug('========== end: generate_l2_perf_logs_multi_lxc ==========')
    perf_timer.stop(msg='l2perf:', start_time=tm_st)
    return collected_logs


def prepare_virtualenv(connection=taf_transport_ssh_wrapper.CONST_CORE_ALIAS, timeout=None):
    logger.info(f"    - prepare virtualenv")
    taf_transport_ssh_wrapper.execute(
        f"pyenv virtualenv-delete -f {VIRTUAL_ENV_NAME}", connection=connection, timeout=timeout)

    taf_transport_ssh_wrapper.execute(
        f"pyenv virtualenv {VIRTUAL_ENV_NAME}", connection=connection, timeout=timeout)

    taf_transport_ssh_wrapper.execute(
        f"{L2PERF_ENV} && cd {L2PERF_PY_PATH} && pip install -r requirements.txt",
        connection=connection, timeout=timeout)


def get_info(connection=taf_transport_ssh_wrapper.CONST_CORE_ALIAS, timeout=None):
    logger.info(f"    - get_info")
    info_str = taf_transport_ssh_wrapper.execute(
        f"{L2PERF_ENV} && cd {L2PERF_PY_PATH} &&  python l2perf.py get_info",
        connection=connection, timeout=timeout)
    if re.search(r"Traceback \(most recent call last\)[\S\s]*TypeError:", info_str) is not None:
        logger.error("    - get_info failed with TypeError")
        return False
    return True


def l2perf_download(cpu, connection=taf_transport_ssh_wrapper.CONST_CORE_ALIAS, timeout=None):
    logger.info(f"    - download")
    taf_transport_ssh_wrapper.execute(
        f"{L2PERF_ENV} &&  cd {L2PERF_PY_PATH} && python l2perf.py download --cpu {cpu}",
        connection=connection,
        timeout=timeout
    )
    return True


def l2perf_install(lxcs, cpu, connection=taf_transport_ssh_wrapper.CONST_CORE_ALIAS, timeout=None):
    logger.info(f"    - install")
    install_str = taf_transport_ssh_wrapper.execute(
        (
            f"{L2PERF_ENV} &&  cd {L2PERF_PY_PATH} && python l2perf.py install "
            f"-l {lxcs.replace(LXC_DELIMITER, ' ')} --cpu {cpu}"
        ),
        connection=connection,
        timeout=timeout,
    )

    if re.search(r"ERROR - Containers with names .* were not found.*", install_str) is not None:
        logger.error("    - l2perf_install failed with invalid containers, please check logs")
        return False
    return True


def collect_logs(lxcs, cpu, logpath=None, connection=taf_transport_ssh_wrapper.CONST_CORE_ALIAS, timeout=None):
    logger.info(f"    - collect_logs")
    collect_logs_str = taf_transport_ssh_wrapper.execute(
        "{} && cd {} && python l2perf.py collect_logs -l {} --cpu {} {}".format(
            L2PERF_ENV,
            L2PERF_PY_PATH,
            lxcs.replace(LXC_DELIMITER, ' '),
            cpu,
            f"-o {logpath}" if logpath else "",
        ), connection=connection, timeout=timeout)

    if re.search(r"ERROR - Containers with names .* were not found.*", collect_logs_str) is not None:
        logger.error("    - collect_logs failed with invalid containers, please check logs")
        return False
    if re.search(r"ERROR - No log files found.", collect_logs_str) is not None:
        logger.error("    - collect_logs failed with No log files found.")
        return False
    if re.search(r"l2perf.py: error: unrecognized arguments.*", collect_logs_str) is not None:
        logger.error("    - collect_logs failed with unrecognized arguments.")
        return False
    return True


def cleanup_folder(directory):
    if os.path.exists(directory):
        for file in os.listdir(directory):
            os.remove(f"{directory}/{file}")


