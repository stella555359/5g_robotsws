#!/bin/bash

# "v1.0 created initially"
echo "bootstrap_test v1.0"
echo "changes bootstrap -110-"

# bootstrap test script
# this script tests the bootstrap script in loop with several
# bootstrap command parameters read from several parameter array's

# due to calling bootstrap with source, bash caller variables are
# handover directly to bootstrap when bootstrap is called w/o parameters
# "source ./bootstrap"   gets $1 $2 $3 ... from bs_bootstrap_test script
# so bs_bootstrap_test script must not have any parameters !!!!!
#
# Instead of command line input varaiables ($1 $2 $3...) this script uses
# several files as input parameters. These files must be located in the
# same directory as bootstrap script:
# test_type.txt  : if not existend, default test type 'param' is choosen
#                : if existend, first line in file shows the test type
#      1st line  : 'param' the test parameter array for bootstrap parameters
#                  is choosen
#                : 'error' the test parameter array for bootstrap error exits
#                  is choosen

# fake_user.txt  : if this file just exists in the same directory as this script
#                  fake user handling of test is invoked. The contents is irrelevant.

# name.txt       : if this file exists, the name taken for virtual environments 
#                  generated by bootstrap is read from first line of file

# this script is located in robotws/testsuite/Ulm/resources/Common/bash/bootstrap
# this script must be run from robotws with command
# source testsuite/Ulm/resources/Common/bash/bootstrap/bootstrap_test.sh


bs_bootstrap_test() {

echo "test for bootstrap v2.0 and higher"

    # test_type.txt is a file which contains in the first line 
    # the test type string to control the execution of this script
    # allowed values: 'param' (default), 'error',
    local test_type="param"
    if [[ -f test_type.txt ]] ; then
        read -r -a line < test_type.txt
        test_type=$line
    fi

    # if fake_user.txt exists fake user handling of test script is invoked
    local fake_user=NO
    if [[ -f fake_user.txt ]] ; then
        fake_user="YES"
    else
        fake_user="NO"
    fi

    # if name.txt exists, the name taken for virtual environments will
    # be read from first line of file
    local name=""
    if [[ -f name.txt ]] ; then
        read -r -a line < name.txt
        name="-n $line"
    fi

    if [[ -z $name ]] && [[ fake_user = YES ]] ; then
        name="fake"
    fi

    echo "------> dry_run=$dry_run"
    echo "------> name=$name"
    echo "------> fake_user=$fake_user"

    if [[ $fake_user = YES ]] ; then
        echo "set fake user must be set before with following cmd:"
        echo "source /mnt/etfiles/users/bin/setuser uic"
        echo "if not press CTRL-C and set the fake user"
        echo "go back to robot workspace and start test again"
    fi
    sleep 5

    local out="out.txt"
    local robot_cmd="time robot --dryrun -o None -r None -l None -V dummy_config.py testsuite/Ulm/resources/Common/ResourceCI"

    local xline="XXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXXX"

    cp $out ${out}.bak
    rm $out


    local dry_run="YES"
    local param=()
    local venv_param=()
    local venv_exec="NO"
    bs_bootstrap_test_get_param  $test_type  dry_run  param  venv_param  venv_exec  $name


    # #param[@] hash is length of array
    local num_tests=${#param[@]}
    echo "NUMBER_OF_TESTS: num_tests=$num_tests"
    echo "TEST TYPE      : test_type=$test_type"
    echo "DRY_RUN        : dry_run  =$dry_run"

    echo "XXXXXXXX PREPARE" >> $out 2>&1
    echo "XXXXXXXX PREPARE"

    if [[ $test_type != error ]] ; then
        pyenv deactivate >> $out 2>&1

        pyenv local 3.6.10  >> $out 2>&1
        pyenv version  >> $out 2>&1
        pip list >> $out 2>&1
        pyenv local 3.9.14  >> $out 2>&1
        pyenv version >> $out 2>&1
        pip list >> $out 2>&1

        pyenv local 2.7.17 >> $out 2>&1
        pyenv versions >> $out 2>&1
    fi

    echo "XXXXXXXX START"  >> $out 2>&1
    echo "XXXXXXXX START"

    local i=0
    for ((i=0;i<num_tests;i++)); do
        echo " "  >> $out 2>&1
        echo "START_IIII=${i}____ $i ____$xline" >> $out 2>&1
        echo "START_IIII=${i}____ $i ____$xline"
        echo " "  >> $out 2>&1
        echo " "

        if [[ $venv_exec != NO ]] ; then
            echo "EXECUTE---->${venv_param[$i]}" >> $out 2>&1
            echo "EXECUTE---->${venv_param[$i]}"
            eval ${venv_param[$i]} >> $out 2>&1
        fi

        pyenv versions >> $out 2>&1
        echo "python version       = $(python -V)"  >> $out 2>&1
        echo "pyenv versio n       = $(pyenv version)" >> $out 2>&1
        echo "VIRTUAL_ENV          = $VIRTUAL_ENV" >> $out 2>&1
        echo "PYENV_VIRTUAL_ENV    = $PYENV_VIRTUAL_ENV" >> $out 2>&1
        echo "PATH                 = $PATH" >> $out 2>&1

        echo "EXECUTE---->source ./bootstrap ${param[$i]}" >> $out 2>&1
        echo "EXECUTE---->source ./bootstrap ${param[$i]}"
        source ./bootstrap ${param[$i]} >> $out 2>&1

        pyenv versions >> $out 2>&1
        echo "python version       = $(python -V)"  >> $out 2>&1
        echo "pyenv version        = $(pyenv version)" >> $out 2>&1
        echo "VIRTUAL_ENV          = $VIRTUAL_ENV" >> $out 2>&1
        echo "PYENV_VIRTUAL_ENV    = $PYENV_VIRTUAL_ENV" >> $out 2>&1
        echo "PATH                 = $PATH" >> $out 2>&1
        echo "ROBOT_SHIMS_LOCATION = $(which robot)" >> $out 2>&1
        echo "ROBOT_LOCATION       = $(pyenv which robot)" >> $out 2>&1

        echo "VIRTUAL_ENV          = $VIRTUAL_ENV"
        echo "ROBOT_SHIMS_LOCATION = $(which robot)"
        echo "ROBOT_LOCATION       = $(pyenv which robot)"

        if [[ $dry_run != NO ]] ; then
            echo "EXECUTE---->DRYRUN" >> $out 2>&1
            echo "EXECUTE---->DRYRUN"
            echo "${robot_cmd}" >> $out 2>&1

            eval ${robot_cmd}   >> $out 2>&1
            if [[ $? = 0 ]] ; then
                echo "____RESULT____ : $i : DRYRUN PASS : bootstrap ${param[$i]}" >> $out 2>&1
                echo "____RESULT____ : $i : DRYRUN PASS : bootstrap ${param[$i]}"
            else
                echo "____RESULT____ : $i : DRYRUN FAIL : bootstrap ${param[$i]}" >> $out 2>&1
                echo "____RESULT____ : $i : DRYRUN FAIL : bootstrap ${param[$i]}"
            fi
        fi

        echo " " >> $out 2>&1
        echo "  END_IIII=${i}____ $i ____ $xline" >> $out 2>&1
    done
    echo " " >> $out 2>&1
    echo "  END_TEST________________$xline" >> $out 2>&1

    echo "deactivate ; pyenv deactivate and do pip list for py 3.6.10 and 3.9.14"  >> $out 2>&1
    echo "deactivate ; pyenv deactivate and do pip list for py 3.6.10 and 3.9.14"

    deactivate >> $out 2>&1
    pyenv deactivate  >> $out 2>&1

    pyenv local 3.6.10  >> $out 2>&1
    pyenv version  >> $out 2>&1
    pyenv version
    pip list  >> $out 2>&1
    pip list
    pyenv local 3.9.14  >> $out 2>&1
    pyenv version  >> $out 2>&1
    pyenv version
    pip list  >> $out 2>&1
    pip list
    pyenv local 2.7.17 >> $out 2>&1
    pyenv versions >> $out 2>&1

    echo "FINISH" >> $out 2>&1
    echo "FINISH"
}


