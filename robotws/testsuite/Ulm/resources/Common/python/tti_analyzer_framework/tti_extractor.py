import os
import pathlib
import re
import tempfile
from itertools import islice
from taf.converters.eventdecoder import EventDecoderConverterFactory
from taf.converters.twdecoder.factory import TwDecoderConverterFactory
from taf.analyzer.ttitrace import TtitraceReader as TtitraceReaderMulti
from taf.analyzer.ttitrace_eventdecoder import TtitraceReader as TtitraceReadereventDecoder


def decode_events_using_multi_decoder(file_name, events_to_analyze, num_of_events=None):
    return [
        event
        for event in islice(
            TtitraceReaderMulti.from_file(
                file_path=file_name),
            num_of_events)
        if event.type in events_to_analyze]


class ConverterFactory(EventDecoderConverterFactory):
    def _create_builtin(self):
        raise AssertionError


def find_json_files_starting_with(basename, pathname):
    """
    Finds all json files in given path named basename.json,
    basename_1.json, basename_2.json, etc. These are files generated by the decoder
    for the tti trace L2Ps component

    :param base_name: prefix for the json filenames
    :param path: path to the eventDecoder application
    :return: list of json files found in pathname with prefix basename
    """
    file_list = [os.path.join(pathname, f) for f in os.listdir(pathname) if re.match(r'%s[_0-9]*\.json' % basename, f)]
    return sorted(file_list)


def create_json_filter(events_to_analyze, target_path=None):
    """
    Create the event filter to pass to the eventDecoder.
    The eventDecoder takes as parameter a text file with the required events
    in each line. This function creates this file.

    :param events_to_analyze: list of required events
    :param target_path: optional path where the filter should be written
    :return: filename to use as filter in eventDecoder with full path
    """
    events = list(dict.fromkeys((events_to_analyze or []) + ["utcTimestampData"]))
    if target_path:
        os.makedirs(os.path.dirname(target_path) or ".", exist_ok=True)
        with open(target_path, "w") as f:
            f.writelines(f"{event}\n" for event in events)
        return target_path

    fd, tmp_path = tempfile.mkstemp(prefix="include_filter_", dir="/tmp", text=True)
    with os.fdopen(fd, "w") as f:
        f.writelines(f"{event}\n" for event in events)
    return tmp_path


def convert_pcap_to_json(file_name, events_to_analyze, tti_dec_path="/opt/tti-dec/tti-dec-bin/",
                         num_of_events=None, filter_json_flag=False, eventdecoder_options='',
                         eventdecoder_stdout_path=''):
    """
    Converts TTI trace in pcap format to json file using event decoder.
    Returns a list of json files created. It can be more than one if we limit the number of
    events the json. If that happens then multiple json files will be created.
    The default number of events is 200k. If you want no limit, pass an empty string in the argument
    eventdecoder_options. If filter_json_flag set to true the json will have only the events
    specified in the list events_to_analyze.

    :param file_name: tti trace pcap filename including full path
    :param tti_dec_path: path to the eventDecoder application
    :param events_to_analyze: list with tti events to be used in filter
    :param eventdecoder_options: options to pass to the eventdecoder
    :param filter_json_flag: True to filter when converting from pcap to json
    :param eventdecoder_stdout_path: std_output.log filename including path
    :return: list of json files created
    """
    factory = ConverterFactory()
    base_name, _ = os.path.splitext(file_name)
    file_path, name = os.path.split(file_name)

    if eventdecoder_stdout_path == '':
        eventdecoder_stdout_path = base_name + '.log'

    if filter_json_flag:
        stdout_dir = os.path.dirname(eventdecoder_stdout_path) or "."
        stdout_stem = os.path.splitext(os.path.basename(eventdecoder_stdout_path))[0]
        include_filename = os.path.join(stdout_dir, f"{stdout_stem}_include_filter.txt")
        include_filename = create_json_filter(events_to_analyze, target_path=include_filename)
        eventdecoder_options += f" --include {include_filename}"

    converter = factory.create(
        configuration=dict(
            input_file_path=file_name,
            output_file_path=base_name,
            output_file_format="json",
            tti_dec_path=tti_dec_path,
            eventdecoder_options=eventdecoder_options,
            eventdecoder_stdout_path=eventdecoder_stdout_path
        ),
        existing_arguments={})
    converter.convert()
    return find_json_files_starting_with(name.split('.')[0], file_path)


def convert_pcap_to_parquetCsv(
        file_name, events_to_analyze=None, tti_dec_path="/opt/tti-dec/tti-dec-bin/",
        tti_dec_venv_path="/opt/tti-dec/venv", filter_parquet_flag=False,
        output_directory=None, decoder_options='', stdout_path='', stderr_path=''):
    """
    Converts TTI trace in pcap format to parquetCsv files using TtiTraceDecoder (twdecoder).
    Returns the path to the output directory that contains the generated ``*_parqCsv_*.csv`` files.

    The output directory defaults to the directory of the input pcap file,
    unless ``output_directory`` or ``--output-directory`` in decoder_options is provided.

    :param file_name: tti trace pcap filename including full path
    :param events_to_analyze: list with tti events to be used in filter
    :param tti_dec_path: path to the tti-dec-bin directory
    :param tti_dec_venv_path: path to the tti-dec virtual environment
    :param filter_parquet_flag: True to filter when converting from pcap to parquet
    :param output_directory: output directory for generated parquetCsv artifacts
    :param decoder_options: additional options to pass to TtiTraceDecoder
    :param stdout_path: file path to write decoder stdout
    :param stderr_path: file path to write decoder stderr
    :return: path to the output directory
    """
    options = 'parquetCsv'
    if decoder_options:
        options += f' {decoder_options}'
    input_path = pathlib.Path(file_name)
    tti_directory = str(input_path.parent)
    if output_directory and '--output-directory' not in options:
        options += f' --output-directory {output_directory}'
        tti_directory = output_directory

    if filter_parquet_flag:
        include_filename = create_json_filter(events_to_analyze)
        options += f' --include {include_filename}'

    if not stdout_path:
        stdout_path = str(input_path.with_suffix('').with_name(input_path.stem + '_twdecoder.log'))
    if not stderr_path:
        stderr_path = str(input_path.with_suffix('').with_name(input_path.stem + '_twdecoder_err.log'))

    factory = TwDecoderConverterFactory()
    converter = factory.create(
        configuration=dict(
            input_file_path=file_name,
            tti_dec_bin_path=tti_dec_path,
            tti_dec_venv_path=tti_dec_venv_path,
            tti_trace_decoder_options=options,
            stdout_path=stdout_path,
            stderr_path=stderr_path,
        ),
        existing_arguments={})
    converter.convert()

    return tti_directory


def convert_pcap_to_parquet(
        file_name, events_to_analyze=None, tti_dec_path="/opt/tti-dec/tti-dec-bin/",
        tti_dec_venv_path="/opt/tti-dec/venv", filter_parquet_flag=False,
        output_directory=None, decoder_options='', stdout_path='', stderr_path=''):
    """
    Converts TTI trace in pcap format to parquet files using TtiTraceDecoder (twdecoder).
    Returns the path to the output directory that contains the generated ``*.parquet`` files.

    :param file_name: tti trace pcap filename including full path
    :param events_to_analyze: list with tti events to be used in filter
    :param tti_dec_path: path to the tti-dec-bin directory
    :param tti_dec_venv_path: path to the tti-dec virtual environment
    :param filter_parquet_flag: True to filter when converting from pcap to parquet
    :param output_directory: output directory for generated parquet artifacts
    :param decoder_options: additional options to pass to TtiTraceDecoder
    :param stdout_path: file path to write decoder stdout
    :param stderr_path: file path to write decoder stderr
    :return: path to the output directory
    """
    options = 'parquet'
    if decoder_options:
        options += f' {decoder_options}'
    if output_directory and '--output-directory' not in options:
        options += f' --output-directory {output_directory}'

    if filter_parquet_flag:
        include_filename = create_json_filter(events_to_analyze)
        options += f' --include {include_filename}'

    file_path = os.path.dirname(file_name)
    base_name, _ = os.path.splitext(file_name)

    if not stdout_path:
        stdout_path = base_name + '_twdecoder.log'
    if not stderr_path:
        stderr_path = base_name + '_twdecoder_err.log'

    factory = TwDecoderConverterFactory()
    converter = factory.create(
        configuration=dict(
            input_file_path=file_name,
            tti_dec_bin_path=tti_dec_path,
            tti_dec_venv_path=tti_dec_venv_path,
            tti_trace_decoder_options=options,
            stdout_path=stdout_path,
            stderr_path=stderr_path,
        ),
        existing_arguments={})
    converter.convert()

    return file_path


def decode_events_using_event_decoder(file_name, events_to_analyze, tti_dec_path="/opt/tti-dec/tti-dec-bin/",
                                      num_of_events=None):
    filtered_events = []
    json_filename_list = convert_pcap_to_json(file_name, events_to_analyze, tti_dec_path, num_of_events)
    for json_filename in json_filename_list:
        with open(json_filename, 'rb') as file_obj:
            for event in islice(TtitraceReadereventDecoder(file_obj=file_obj), num_of_events):
                if event.type in events_to_analyze:
                    filtered_events.append(event)
    return filtered_events


def ttieventextractor(file_name, events_to_analyze, useMultiDecoder, num_of_events=None):
    if useMultiDecoder:
        return decode_events_using_multi_decoder(file_name, events_to_analyze, num_of_events=None)
    else:
        file_name = file_name.replace("udp", "pcap")
        return decode_events_using_event_decoder(file_name, events_to_analyze, num_of_events=None)
