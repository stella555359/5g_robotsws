from robot.libraries.BuiltIn import BuiltIn
from testsuite.Oulu.TrunkEng.Common.Python.Interfaces.Logger import info, warning, error


class FaultingSMOD:

    def __init__(self):
        self.alarms = BuiltIn().get_library_instance("ALARMS")

    def generate_fault_to_smod_soc(self, sci, soc="Marlin", application="CCSDaemonExe", all_containers=False,
                                   only_fault_id=False):
        """
        Supports ASOE/ASOG/ASOH, as they do not have BBMOD attached but internal SoC.
        The controller SoC is Marlin and the interface SoC is Thor.

        The fault is generated by killing CCSDaemonExe from the internal SoC.
        """
        applications = BuiltIn().get_library_instance("APPLICATIONS")
        if not any(smod for smod in ["ASOE", "ASOH", "ASOG"] if smod in sci.name):
            warning(f"Generate Fault To SMOD SoC -KW supports only ASOE/G/H. You are "
                    f"running test with {sci.name} so functionality is not guaranteed.")

        if soc == "Marlin":
            info(f"Kill application {application} from SMOD controller SoC (Marlin)")
            applications.kill_application_from_smod_controller_soc(application)
            self.alarms.add_expected_alarm(fault_id="4590", fault_name="Fault signature for crash or failure")
        else:
            info(f"Kill application {application} from SMOD interface SoC (Thor)")
            if not all_containers:
                applications.kill_application_from_smod_interface_soc(application)
            else:
                applications.kill_application_from_smod_interface_soc_all_containers(application)
            if application == "CCSEmDispatcherExe":
                if not only_fault_id:
                    self.alarms.add_expected_alarm(
                        fault_id="4383", fault_name="Internal BTS processes autonomous reset as recovery action")
                else:
                    info(f"not adding alarm for CCSEmDispatcherExe since it is done in robot keyword: "
                         f"Crash interface SOC from SMOD with expected alarm")
            else:
                if not only_fault_id:
                    self.alarms.add_expected_alarm(fault_id="2087",
                                                   fault_name="SoC autonomous reset as recovery action",
                                                   reason="Secondary SoC_B autonomous reset")
                else:
                    self.alarms.add_expected_alarm(fault_id="2087")
